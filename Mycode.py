# รับค่าน้ำหนัก (กิโลกรัม) และส่วนสูง (เมตร) จากผู้ใช้
weight = float(input("กรอกน้ำหนักตัว (กิโลกรัม): "))
height = float(input("กรอกส่วนสูง (เมตร เช่น 1.75): "))

# คำนวณค่า BMI (น้ำหนัก / ส่วนสูงยกกำลังสอง)
bmi = weight / (height ** 2)

# แสดงผลค่า BMI ที่ได้ (ปัดเศษ 2 ตำแหน่ง)
print(f"ค่า BMI ของคุณคือ: {bmi:.2f}")

# ตรวจสอบเกณฑ์มาตรฐาน
if bmi < 18.5:
    print("เกณฑ์: น้ำหนักน้อย / ผอม")
elif 18.5 <= bmi < 23:
    print("เกณฑ์: ปกติ / สมส่วน")
elif 23 <= bmi < 25:
    print("เกณฑ์: ท้วม / น้ำหนักเกิน")
elif 25 <= bmi < 30:
    print("เกณฑ์: อ้วนระดับ 1")
else:
    print("เกณฑ์: อ้วนระดับ 2 / อ้วนอันตราย")
